const fixture = `openapi: 3.0.3
info: {title: t, version: "1"}
paths: {}
components:
  schemas:
    Client:
      type: object
      description: An OAuth client.
      required: [client_id, redirect_uris]
      properties:
        client_id: {type: string}
        redirect_uris: {type: array, items: {type: string}}
        allow_persistent_sessions: {type: boolean, description: People may stay signed in.}
        created_at: {type: string, format: date-time}
        theme: {$ref: '#/components/schemas/Theme'}
        metadata: {type: object, additionalProperties: {type: string}}
        extra: {type: object}
        limits:
          type: object
          properties:
            max: {type: integer}
        tags:
          type: array
          items:
            type: object
            properties:
              name: {type: string}
        either:
          oneOf: [{type: string}, {type: integer}]
        reason: {type: string, nullable: true}
        ratio: {type: number}
    Theme:
      type: object
      properties:
        color: {type: string}
    Kind:
      type: string
      enum: [customer, supplier]
    Member:
      allOf:
        - $ref: '#/components/schemas/Theme'
        - type: object
          required: [role]
          properties:
            role: {type: string}
    Ids:
      type: array
      items: {type: string}
`

func generate(t *testing.T) string {
	t.Helper()
	d, err := oas.Load([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	src, err := Generate(d, "cauthyapi", "openapi/cauthy.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}

func TestGenerateWritesOneTypePerSchema(t *testing.T) {
	src := generate(t)
	flat := strings.Join(strings.Fields(src), " ")
	for _, want := range []string{
		"// Code generated by gen-apitypes from openapi/cauthy.yaml. DO NOT EDIT.",
		`import "encoding/json"`,
		"// An OAuth client. type Client struct {",
		"ClientID string `json:\"client_id\"`",
		"RedirectURIs []string `json:\"redirect_uris\"`",
		"// People may stay signed in. AllowPersistentSessions *bool `json:\"allow_persistent_sessions,omitempty\"`",
		"CreatedAt *string `json:\"created_at,omitempty\"`",
		"Theme *Theme `json:\"theme,omitempty\"`",
		"Metadata map[string]string `json:\"metadata,omitempty\"`",
		"Extra map[string]any `json:\"extra,omitempty\"`",
		"Limits *ClientLimits `json:\"limits,omitempty\"`",
		"type ClientLimits struct { Max *int64 `json:\"max,omitempty\"` }",
		"Tags []ClientTagsItem `json:\"tags,omitempty\"`",
		"type ClientTagsItem struct { Name *string `json:\"name,omitempty\"` }",
		"Either json.RawMessage `json:\"either,omitempty\"`",
		"Reason *string `json:\"reason,omitempty\"`",
		"Ratio *float64 `json:\"ratio,omitempty\"`",
		"type Kind string",
		`KindCustomer Kind = "customer"`,
		`KindSupplier Kind = "supplier"`,
		"type Member struct { Theme Role string `json:\"role\"` }",
		"type IDs []string",
	} {
		if !strings.Contains(flat, want) {
			t.Errorf("want %q in:\n%s", want, src)
		}
	}
}

func TestGeneratedCodeTypeChecks(t *testing.T) {
	src := generate(t)
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "types.gen.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil)}
	if _, err := conf.Check("cauthyapi", fset, []*ast.File{f}, nil); err != nil {
		t.Fatalf("%v\n%s", err, src)
	}
}

func TestGenerateIsDeterministic(t *testing.T) {
	if generate(t) != generate(t) {
		t.Fatal("two runs differ")
	}
}
