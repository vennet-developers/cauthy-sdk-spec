// Package apigen writes Go types for the schemas of an OpenAPI document: one
// named type per components.schemas entry, plus one per inline object, using
// the standard library only. An optional field is a pointer (slices and maps
// stay as they are) with omitempty; oneOf and anyOf become json.RawMessage,
// for the caller to decode; allOf embeds what it references.
package apigen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/vennet-developers/cauthy-sdk-spec/conformance/internal/oas"
)

type gen struct {
	doc      *oas.Doc
	decls    map[string]string // type name → its declaration
	taken    map[string]bool   // names in use
	usesJSON bool
}

// Generate answers the source of package pkg, gofmt'ed. source names the
// document in the header.
func Generate(d *oas.Doc, pkg, source string) ([]byte, error) {
	g := &gen{doc: d, decls: map[string]string{}, taken: map[string]bool{}}
	names := make([]string, 0, len(d.Schemas))
	for n := range d.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		tn := GoName(n)
		if g.taken[tn] {
			return nil, fmt.Errorf("apigen: two schemas become the Go type %s", tn)
		}
		g.taken[tn] = true
	}
	for _, n := range names {
		if err := g.declare(GoName(n), d.Schemas[n]); err != nil {
			return nil, err
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen-apitypes from %s. DO NOT EDIT.\n\npackage %s\n\n", source, pkg)
	if g.usesJSON {
		b.WriteString("import \"encoding/json\"\n\n")
	}
	decls := make([]string, 0, len(g.decls))
	for n := range g.decls {
		decls = append(decls, n)
	}
	sort.Strings(decls)
	for _, n := range decls {
		b.WriteString(g.decls[n])
		b.WriteString("\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("apigen: the generated code does not parse: %w", err)
	}
	return src, nil
}

func isStruct(s *oas.Schema) bool { return len(s.Properties) > 0 || len(s.AllOf) > 0 }

// declare writes the declaration of the named type.
func (g *gen) declare(name string, s *oas.Schema) error {
	var b strings.Builder
	comment(&b, "", s.Description)
	switch {
	case s.Ref != "":
		ref, ok := oas.RefName(s.Ref)
		if !ok {
			return fmt.Errorf("apigen: %s: $ref %s", name, s.Ref)
		}
		fmt.Fprintf(&b, "type %s = %s\n", name, GoName(ref))
	case s.Type == "string" && len(s.Enum) > 0:
		fmt.Fprintf(&b, "type %s string\n\nconst (\n", name)
		seen := map[string]bool{}
		for _, v := range s.Enum {
			c := name + GoName(fmt.Sprint(v))
			for g.taken[c] || seen[c] {
				c += "Value"
			}
			seen[c] = true
			fmt.Fprintf(&b, "\t%s %s = %q\n", c, name, fmt.Sprint(v))
		}
		b.WriteString(")\n")
	case isStruct(s):
		body, err := g.structOf(name, s)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "type %s %s\n", name, body)
	default:
		t, err := g.goType(s, name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "type %s %s\n", name, t)
	}
	g.decls[name] = b.String()
	return nil
}

type field struct {
	json     string
	schema   *oas.Schema
	required bool
}

func (g *gen) structOf(name string, s *oas.Schema) (string, error) {
	var b strings.Builder
	b.WriteString("struct {\n")
	var fields []field
	seen := map[string]bool{}
	addFrom := func(x *oas.Schema) {
		req := map[string]bool{}
		for _, r := range x.Required {
			req[r] = true
		}
		for _, p := range x.PropertyOrder {
			if !seen[p] {
				seen[p] = true
				fields = append(fields, field{p, x.Properties[p], req[p]})
			}
		}
	}
	for _, part := range s.AllOf {
		if part.Ref == "" {
			addFrom(part)
			continue
		}
		ref, ok := oas.RefName(part.Ref)
		if !ok {
			return "", fmt.Errorf("apigen: %s: allOf $ref %s", name, part.Ref)
		}
		fmt.Fprintf(&b, "\t%s\n", GoName(ref))
	}
	addFrom(s)
	goNames := map[string]bool{}
	for _, f := range fields {
		t, err := g.goType(f.schema, name+GoName(f.json))
		if err != nil {
			return "", err
		}
		fn := GoName(f.json)
		for goNames[fn] {
			fn += "_"
		}
		goNames[fn] = true
		tag := f.json
		switch {
		case !f.required:
			t, tag = optional(t), tag+",omitempty"
		case f.schema != nil && f.schema.Nullable:
			t = optional(t)
		}
		if f.schema != nil {
			comment(&b, "\t", f.schema.Description)
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", fn, t, tag)
	}
	b.WriteString("}")
	return b.String(), nil
}

// goType is the Go type of a schema; hint names an inline object's type.
func (g *gen) goType(s *oas.Schema, hint string) (string, error) {
	if s == nil {
		return "any", nil
	}
	if s.Ref != "" {
		ref, ok := oas.RefName(s.Ref)
		if !ok {
			return "", fmt.Errorf("apigen: %s: $ref %s", hint, s.Ref)
		}
		return GoName(ref), nil
	}
	if len(s.OneOf)+len(s.AnyOf) > 0 {
		g.usesJSON = true
		return "json.RawMessage", nil
	}
	if len(s.AllOf) == 1 && len(s.Properties) == 0 {
		return g.goType(s.AllOf[0], hint)
	}
	if isStruct(s) {
		name := g.fresh(hint)
		if err := g.declare(name, s); err != nil {
			return "", err
		}
		return name, nil
	}
	switch s.Type {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		t, err := g.goType(s.Items, hint+"Item")
		if err != nil {
			return "", err
		}
		return "[]" + t, nil
	case "object", "":
		if s.AdditionalProperties != nil && s.AdditionalProperties.Schema != nil {
			t, err := g.goType(s.AdditionalProperties.Schema, hint+"Value")
			if err != nil {
				return "", err
			}
			return "map[string]" + t, nil
		}
		if s.Type == "object" {
			return "map[string]any", nil
		}
		return "any", nil
	}
	return "", fmt.Errorf("apigen: %s has the unknown type %q", hint, s.Type)
}

// fresh reserves a type name for an inline object.
func (g *gen) fresh(hint string) string {
	name := hint
	for i := 2; g.taken[name]; i++ {
		name = fmt.Sprintf("%s%d", hint, i)
	}
	g.taken[name] = true
	return name
}

// optional is the type of a field that may be absent or null.
func optional(t string) string {
	switch {
	case strings.HasPrefix(t, "[]"), strings.HasPrefix(t, "map["), strings.HasPrefix(t, "*"), t == "any", t == "json.RawMessage":
		return t
	}
	return "*" + t
}

func comment(b *strings.Builder, indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		if line = strings.TrimRight(line, " \t"); line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}
