// gen-vectors writes vectors/jwks.json and vectors/tokens.json from the
// test-only keys in vectors/keys. The same keys always give the same bytes.
//
//	go run ./cmd/gen-vectors ../vectors/keys ../vectors     write the vectors
//	go run ./cmd/gen-vectors -make-keys ../vectors/keys     write missing key files, then stop
package main

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"flag"
	"fmt"
	"math/big"
	"os"
	"path/filepath"

	"github.com/vennet-developers/cauthy-sdk-spec/conformance/internal/vectors"
)

var b64 = base64.RawURLEncoding

func main() {
	makeKeys := flag.Bool("make-keys", false, "write the key files missing in <keys dir>, then stop")
	flag.Usage = func() {
		fmt.Fprintln(os.Stderr, "usage: gen-vectors <keys dir> <out dir>\n       gen-vectors -make-keys <keys dir>")
	}
	flag.Parse()
	if *makeKeys {
		if flag.NArg() != 1 {
			flag.Usage()
			os.Exit(2)
		}
		if err := MakeKeys(flag.Arg(0)); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if flag.NArg() != 2 {
		flag.Usage()
		os.Exit(2)
	}
	keys, err := LoadKeys(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	jwks, tokens := Generate(keys)
	for name, raw := range map[string][]byte{"jwks.json": jwks, "tokens.json": tokens} {
		if err := os.WriteFile(filepath.Join(flag.Arg(1), name), raw, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

// encode writes v as indented JSON with a final newline, leaving <, > and &
// as they are.
func encode(v any) []byte {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		panic(err)
	}
	return b.Bytes()
}

// publicJWK is a key as the JWKS publishes it, in Cauthy's field order.
type publicJWK struct {
	Kty string `json:"kty"`
	Use string `json:"use"`
	Alg string `json:"alg"`
	Kid string `json:"kid"`
	N   string `json:"n"`
	E   string `json:"e"`
}

func publicOf(k Keys, keyKid, kid, use string) publicJWK {
	pub := k[keyKid].PublicKey
	return publicJWK{Kty: "RSA", Use: use, Alg: "RS256", Kid: kid, N: b64int(pub.N), E: b64int(big.NewInt(int64(pub.E)))}
}

// Generate answers jwks.json and tokens.json.
func Generate(k Keys) (jwks, tokens []byte) {
	jwks = encode(map[string][]publicJWK{"keys": {
		publicOf(k, KidA, KidA, "sig"),
		publicOf(k, KidB, KidB, "sig"),
		publicOf(k, KidWeak, KidWeak, "sig"),
		publicOf(k, KidAttacker, KidEnc, "enc"),
	}})
	tokens = encode(vectors.File{
		Comment:       "GENERATED by conformance/cmd/gen-vectors from the test-only keys in vectors/keys. Do not edit. The rules are verification/rules.md.",
		Version:       1,
		LeewaySeconds: 30,
		MaxTokenBytes: 8192,
		Cases:         Cases(k),
	})
	return jwks, tokens
}
